#!/usr/bin/env python3
"""Gzip www-c2 assets into PROGMEM C headers.

Blockly is packed as a core-only IIFE (no standard blocks, generators, or
Zelos) so the OTA image fits a 1280 KB default ESP32 slot.
"""

from __future__ import annotations

import gzip
import shutil
import subprocess
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WWW = ROOT / "www-c2"
OUT = ROOT / "include" / "www-c2"
BLOCKLY_CORE_URL = (
    "https://cdn.jsdelivr.net/npm/blockly@10.4.3/blockly_compressed.js"
)
SLIM_MIN = 80_000
SLIM_MAX = 650_000

ASSETS = [
    (WWW / "index.html", "c2_index.h", "c2_index_html_gz"),
    (WWW / "c2.css", "c2_css.h", "c2_css_gz"),
    (WWW / "c2.js", "c2_js.h", "c2_js_gz"),
    (WWW / "blockly.min.js", "c2_blockly.h", "c2_blockly_js_gz"),
]


def _build_slim_blockly(dest: Path) -> None:
    npx = shutil.which("npx")
    npm = shutil.which("npm")
    if not npx or not npm:
        raise RuntimeError("npx/npm required to slim Blockly")
    with tempfile.TemporaryDirectory(prefix="c2-blockly-") as tmp:
        work = Path(tmp)
        (work / "package.json").write_text(
            '{"name":"c2-blockly-slim","private":true}\n', encoding="utf-8"
        )
        (work / "entry.mjs").write_text(
            'import * as Blockly from "blockly/core";\n'
            "globalThis.Blockly = Blockly;\n",
            encoding="utf-8",
        )
        subprocess.check_call(
            [npm, "install", "--silent", "blockly@10.4.3", "esbuild@0.25.0"],
            cwd=work,
        )
        subprocess.check_call(
            [
                npx,
                "--no-install",
                "esbuild",
                "entry.mjs",
                "--bundle",
                "--minify",
                "--format=iife",
                f"--outfile={dest}",
            ],
            cwd=work,
        )


def ensure_blockly() -> None:
    dest = WWW / "blockly.min.js"
    if dest.exists() and SLIM_MIN <= dest.stat().st_size <= SLIM_MAX:
        return
    print("Building slim Blockly core…")
    dest.parent.mkdir(parents=True, exist_ok=True)
    try:
        _build_slim_blockly(dest)
        return
    except (OSError, subprocess.CalledProcessError, RuntimeError) as err:
        print(f"Slim build failed ({err}); downloading Blockly core…")
    urllib.request.urlretrieve(BLOCKLY_CORE_URL, dest)


def pack(src: Path, header_name: str, var_name: str) -> None:
    compressed = gzip.compress(src.read_bytes(), compresslevel=9)
    lines = [
        f"// Generated by tools/pack_c2.py at {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"// File: {src.name}.gz, Size: {len(compressed)}",
        f"#define {var_name}_len {len(compressed)}",
        f"const uint8_t {var_name}[] PROGMEM = {{",
    ]
    hex_values = [f"0x{byte:02x}" for byte in compressed]
    width = 12
    for i in range(0, len(hex_values), width):
        chunk = hex_values[i : i + width]
        comma = "," if i + width < len(hex_values) else ""
        lines.append(f"    {', '.join(chunk)}{comma}")
    lines.append("};")
    out = OUT / header_name
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{src.name}: {len(compressed)} gzip bytes -> {out}")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    ensure_blockly()
    for src, header, var in ASSETS:
        pack(src, header, var)


if __name__ == "__main__":
    main()
